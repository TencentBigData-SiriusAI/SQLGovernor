-- ============================================================================
-- Case 06: 时间窗口偏移
-- ============================================================================
-- 【问题描述】
--   查询的时间范围与业务想要的时间范围不一致，常见错误包括：
--     1. BETWEEN 包含两端导致多查了一天（查 8 天而非 7 天）
--     2. 分区日期范围与 WHERE 中时间戳条件的范围不对齐
--     3. 跨天数据的时间戳与分区日期归属不一致
--     4. 月末/月初的日期计算边界错误
--     5. 分区条件漏写导致全表扫描
--
-- 【易犯场景】
--   1. 想查"最近7天"用 BETWEEN，但包含首尾两端实际查了 8 天
--   2. 分区过滤了 3.1~3.7，但时间戳条件写了 3.2 0:00 之后
--   3. 23:59 的数据分区在当天，但时间戳可能跨到第二天
--
-- 【预期诊断结果】
--   应触发"业务意图不匹配"告警：
--   - 查询时间范围可能与业务意图的时间窗口不一致
--   - BETWEEN 包含两端，实际范围比预期多一天
-- ============================================================================


-- ---------------------------------------------------------------------------
-- Case 6a: BETWEEN 包含两端导致查了 8 天而非 7 天
-- 业务需求：查询最近 7 天（3月2日～3月8日）的 App 数据
-- ❌ 错误：BETWEEN '20260302' AND '20260308' 包含两端，
--   实际覆盖 3.2/3.3/3.4/3.5/3.6/3.7/3.8 共 7 天，看似正确，
--   但如果需求是"3月8日往前7天"即 3.1~3.7，就多了 3.8 少了 3.1
-- ---------------------------------------------------------------------------
SELECT
    a.dt,
    COUNT(*)                                                 AS app_count,
    COUNT(CASE WHEN a.`result` = 0 THEN 1 END)                AS success_count
FROM spark_analytics.spark_app_metrics a
WHERE a.dt BETWEEN '20260302' AND '20260308'
GROUP BY a.dt
ORDER BY a.dt;
-- ❌ 业务说"3月8日往前7天"，应该是 3.1~3.7（不含 3.8）
-- ❌ BETWEEN 包含两端，这里查的是 3.2~3.8，既多了 3.8 又少了 3.1
-- ✅ 正确写法：使用 >= 和 < 精确控制范围
-- WHERE a.dt >= '20260301' AND a.dt < '20260308'


-- ---------------------------------------------------------------------------
-- Case 6b: 分区日期范围与时间戳条件不对齐
-- 业务需求：查询 3月8日当天 9:00~18:00 的 App 数据
-- ❌ 错误：分区过滤了 3.7 和 3.8 两天，但时间戳条件只对齐 3.8，
--   3.7 的数据没有时间戳过滤，全部被包含进来
-- ---------------------------------------------------------------------------
SELECT
    a.app_id,
    a.app_name,
    a.start_time,
    a.end_time
FROM spark_analytics.spark_app_metrics a
WHERE a.dt IN ('20260307', '20260308')
  AND a.start_time >= 1741398000000
  AND a.start_time < 1741430400000;
-- ❌ 分区包含了 20260307，但时间戳范围是 3.8 的 9:00~18:00
-- ❌ 20260307 分区的数据如果 start_time 恰好在该范围内也会被选中
-- ❌ 分区范围和时间戳范围不对齐，语义混乱
-- ✅ 正确写法：分区只用 20260308，时间戳条件对齐
-- WHERE a.dt = '20260308'
--   AND a.start_time >= 1741398000000
--   AND a.start_time < 1741430400000


-- ---------------------------------------------------------------------------
-- Case 6c: 跨天数据的时间戳与分区日期归属不一致
-- 业务需求：统计 3月8日的 Job 运行情况
-- ❌ 错误：分区用 20260308，但有些 job 的 start_time 在 3.7 23:xx，
--   end_time 在 3.8，这些跨天 job 的分区归属可能不在 20260308
-- ---------------------------------------------------------------------------
SELECT
    j.app_id,
    j.job_id,
    j.start_time,
    j.end_time,
    (j.end_time - j.start_time)                              AS duration_ms
FROM spark_analytics.spark_job_metrics j
WHERE j.dt = '20260308'
  AND j.start_time >= 1741363200000
  AND j.end_time < 1741449600000
ORDER BY duration_ms DESC
LIMIT 100;
-- ❌ 分区 20260308 可能不包含"3.7 晚开始、3.8 凌晨结束"的跨天 job
-- ❌ 这些 job 可能在 20260307 分区中，导致统计遗漏
-- ✅ 正确写法：同时查 3.7 和 3.8 两天分区
-- WHERE j.dt IN ('20260307', '20260308')
--   AND j.end_time >= 1741363200000 AND j.end_time < 1741449600000


-- ---------------------------------------------------------------------------
-- Case 6d: 月末/月初的日期计算边界错误
-- 业务需求：查询 2026 年 2 月份（整月）的 App 数据
-- ❌ 错误：2026 年非闰年，2 月只有 28 天，但 BETWEEN 写到了 0229
-- ---------------------------------------------------------------------------
SELECT
    a.dt,
    COUNT(*)                                                 AS app_count
FROM spark_analytics.spark_app_metrics a
WHERE a.dt BETWEEN '20260201' AND '20260229'
GROUP BY a.dt
ORDER BY a.dt;
-- ❌ 2026 年不是闰年，2 月只有 28 天，20260229 不存在
-- ❌ 虽然不会报错（STRING 比较），但语义上制造了混淆
-- ✅ 正确写法：用 20260228 或用 < '20260301'
-- WHERE a.dt >= '20260201' AND a.dt < '20260301'


-- ---------------------------------------------------------------------------
-- Case 6e: 分区条件漏写导致扫了全量历史数据
-- 业务需求：统计 3月8日各 App 的 Stage 耗时
-- ❌ 错误：app 表加了分区条件，但 stage 表忘记加分区条件，
--   导致 stage 表扫描全量历史数据
-- ---------------------------------------------------------------------------
SELECT
    a.app_id,
    a.app_name,
    COUNT(s.stage_id)                                        AS stage_count,
    AVG(s.end_time - s.start_time)                           AS avg_stage_duration
FROM spark_analytics.spark_app_metrics a
INNER JOIN spark_analytics.spark_stage_metrics s
    ON a.app_id = s.app_id
WHERE a.dt = '20260308'
GROUP BY a.app_id, a.app_name
ORDER BY avg_stage_duration DESC
LIMIT 50;
-- ❌ stage 表没有分区过滤条件，会扫描全量历史分区
-- ❌ stage 表的历史数据也会被 JOIN 进来，结果包含非当天的 stage
-- ✅ 正确写法：stage 表也加分区条件
-- ON a.app_id = s.app_id AND a.dt = s.dt
-- 或在 WHERE 中加 AND s.dt = '20260308'
